// The client logs through webpack's own `Logger` and `createConsoleLogger`,
// which are node-side source: classes, `const`, spread. Bundled for a page as
// they are, an `["web", "es5"]` build carries that syntax to a browser that
// cannot parse it, and webpack does not transpile `node_modules`. So the built
// client gets ES5 copies of the two next to it, and `babel.config.js` points
// its import at them; the source checkout keeps importing webpack's directly.
import { mkdir, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { transformFileAsync } from "@babel/core";

// Not `import.meta.dirname`: this package supports node.js 20.9, which does not
// have it.
const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "client", "modules", "logger");
const require = createRequire(import.meta.url);

await mkdir(OUT, { recursive: true });

for (const name of ["Logger", "createConsoleLogger"]) {
  const source = require.resolve(`webpack/lib/logging/${name}.js`);
  const result = await transformFileAsync(source, {
    babelrc: false,
    configFile: false,
    // CommonJS as webpack wrote it; only the syntax is lowered.
    sourceType: "script",
    presets: [["@babel/preset-env", { modules: false, targets: { ie: "11" } }]],
  });

  // `.cjs`, because `client/` is marked as ES modules and these are not; the
  // one require between them has to name the renamed file.
  const code = /** @type {string} */ (result && result.code).replaceAll(
    'require("./Logger")',
    'require("./Logger.cjs")',
  );

  await writeFile(
    path.join(OUT, `${name}.cjs`),
    `// Generated by scripts/build-client-logger.mjs from webpack/lib/logging/${name}.js — do not edit.\n${code}\n`,
  );
}
